#!/usr/bin/env node
// Generates src/resume-render/fonts/fonts.css from @fontsource packages: woff2 only, Latin fonts
// limited to latin + latin-ext, CJK fonts keep every unicode-range slice. Run after upgrading fonts:
//   node scripts/build-resume-fonts.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const out = join(root, 'src/resume-render/fonts/fonts.css')

const FONTS = [
  { pkg: 'noto-sans-sc', styles: [['normal', [400, 500, 700]]], cjk: true },
  { pkg: 'noto-serif-sc', styles: [['normal', [400, 700]]], cjk: true },
  { pkg: 'inter', styles: [['normal', [300, 400, 500, 600, 700]]] },
  { pkg: 'source-serif-4', styles: [['normal', [400, 600, 700]], ['italic', [400]]] },
  { pkg: 'jetbrains-mono', styles: [['normal', [400, 500]]] },
]
const LATIN_SUBSETS = new Set(['latin', 'latin-ext'])

const rules = []
for (const font of FONTS) {
  const dir = join(root, 'node_modules/@fontsource', font.pkg)
  for (const [style, weights] of font.styles) {
    for (const weight of weights) {
      const css = readFileSync(join(dir, `${weight}${style === 'italic' ? '-italic' : ''}.css`), 'utf8')
      for (const match of css.matchAll(/\/\* ([^*]+) \*\/\s*@font-face \{([^}]+)\}/g)) {
        const [, name, body] = match
        const subset = name.replace(`${font.pkg}-`, '').replace(/-\d+-(normal|italic)$/, '')
        if (!font.cjk && !LATIN_SUBSETS.has(subset)) continue
        const family = /font-family: '([^']+)'/.exec(body)[1]
        const woff2 = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(body)[1]
        const range = /unicode-range: ([^;]+);/.exec(body)?.[1]
        const url = relative(dirname(out), join(dir, 'files', woff2)).split('\\').join('/')
        rules.push(`@font-face{font-family:'${family}';font-style:${style};font-weight:${weight};font-display:block;src:url(${url}) format('woff2')${range ? `;unicode-range:${range}` : ''}}`)
      }
    }
  }
}

writeFileSync(out, `/* Generated by scripts/build-resume-fonts.mjs: resume fonts, static weights, woff2 only (docs/phase2/02 §4.2). */\n${rules.join('\n')}\n`)
console.log(`${rules.length} @font-face rules → ${relative(root, out)}`)
